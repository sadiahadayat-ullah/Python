num = input("Enter a number: ")
print("Original Value:",num)
print("Original type:",type(num))
# Convert to Integer
Integer_num = int(num)
print("Integer Value:",Integer_num)
print("Type:",type(Integer_num))
# Convert to Float
Float_num = float(num)
print("Float Value:",Float_num)
print("Type:",type(Float_num))
# Convert back to string
String_num = str(num)
print("String Value:",String_num)
print("Type:",type(String_num))