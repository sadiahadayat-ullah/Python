numbers = (10,20,30,40,50)
# Print the complete tuple
print(numbers)
# Elements from index 1 to 3
print(numbers[1:4])
# Elements from beginning to index 3
print(numbers[:4])
# Elements from index 2 to end
print(numbers[2:])
# Every second element
print(numbers[::2])
# Reverse the tuple
print(numbers[::-1])
# Copy the tuple
print(numbers[:])
# Last three elements
print(numbers[-3:])
# All except last three elements
print(numbers[:-3])